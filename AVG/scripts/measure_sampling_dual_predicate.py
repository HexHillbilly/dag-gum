# Report context builder (shared by measurement and --report-only)
# ---------------------------------------------------------------------------
def build_ctx_from_results(
    all_results: List[Dict[str, Any]],
    ds035_rates: Dict[str, float],
    night008_fire: Dict[str, Dict[str, int]],
    ds032_part2: List[Dict[str, Any]],
    device: str,
    dtype: Any,
    smoke: Dict[str, Any],
    spectral_threshold: float,
    wall_clock_s: float,
) -> Dict[str, Any]:
    """Build the report context from per-record results (single source of truth)."""
    fixture_names = ["t2s_degenerate", "qwen_degenerate", "heldout_degenerate_v2"]

    comparison: Dict[str, Dict[str, Any]] = {}
    escape: Dict[str, Dict[str, Any]] = {}
    dormant_agg: Dict[str, Dict[str, Any]] = {}

    for fixture in fixture_names:
        recs = [r for r in all_results if r["fixture"] == fixture]
        arm1_agg = aggregate_arm(recs, "arm1_active")
        arm2_agg = aggregate_arm(recs, "arm2_active")
        escape[fixture] = {
            "arm1_agg": arm1_agg,
            "arm2_agg": arm2_agg,
        }
        if fixture == "heldout_degenerate_v2":
            escape[fixture]["ds032_part2"] = compute_ds032_part2_metrics(
                ds032_part2
            )
        comparison[fixture] = {
            "greedy_rate": float(ds035_rates.get(fixture, float("nan"))),
            "arm1_rate": float(arm1_agg["rescue_rate"]),
            "arm2_rate": float(arm2_agg["rescue_rate"]),
        }
        dorm_recs = [r["dormant"] for r in recs]
        dormant_agg[fixture] = {
            "n_records": len(dorm_recs),
            "mean_n_gen": mean_or_nan([d["n_generated"] for d in dorm_recs]),
            "mean_d2": mean_or_nan([d["distinct_2"] for d in dorm_recs]),
            "source": dorm_recs[0]["source"] if dorm_recs else "n/a",
        }

    tables = {
        "comparison": comparison,
        "escape": escape,
        "dormant": dormant_agg,
        "fire_greedy": night008_fire,
    }
    metadata = {
        "model_name": MODEL_NAME,
        "model_revision": MODEL_REVISION,
        "device": device,
        "dtype": str(dtype),
        "torch_version": torch.__version__,
        "seed": SEED,
        "max_new_tokens": MAX_NEW_TOKENS,
        "analysis_window": ANALYSIS_WINDOW,
        "hook_layer": HOOK_LAYER,
        "band_low": spectral_threshold,
        "bmm_override": "deregistered",
        "wall_clock_s": wall_clock_s,
    }
    return {
        "metadata": metadata,
        "determinism_smoke": smoke,
        "tables": tables,
        "results": all_results,
    }


