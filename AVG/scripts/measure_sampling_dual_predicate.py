def run_determinism_smoke(
    model: torch.nn.Module,
    tokenizer: Any,
    records_c: List[Dict[str, Any]],
    prompt_key: str,
    non_prose_ids: Set[int],
    spectral_threshold: float,
) -> Dict[str, Any]:
    """Determinism smoke (night-014): one Fixture C record.
      1. Dormant sampling generated twice with SEED=42 — token ids must match.
      2. Arm 1 active generated twice — token ids AND per-step PR log must
         match to 6 decimal places.
    The smoke record is the FIRST Fixture C record where Arm 1 reaches the
    analysis window (n_generated >= 24), so the PR-log identity check is
    non-vacuous. STOP (sys.exit 1) if either check fails.
    """
    # Find a Fixture C record where Arm 1 reaches the analysis window so the
    # PR-log determinism check is meaningful (immediate-EOS records have an
    # empty PR log).
    smoke_record: Optional[Dict[str, Any]] = None
    rid = -1
    prompt = ""
    for rec in records_c:
        probe = sampling_generate_active(
            model, tokenizer, rec[prompt_key], non_prose_ids,
            spectral_threshold, kickstart_mode="production",
        )
        if probe["n_generated"] >= ANALYSIS_WINDOW and probe["n_pr_values"] > 0:
            smoke_record = rec
            rid = int(rec["id"])
            prompt = rec[prompt_key]
            print(f"  smoke record: Fixture C record_id={rid} "
                  f"(arm1 probe n_gen={probe['n_generated']}, "
                  f"n_pr={probe['n_pr_values']})")
            break
    if smoke_record is None:
        print("[STOP] Determinism smoke: no Fixture C record reached the "
              "analysis window under Arm 1. Cannot verify PR-log determinism.")
        sys.exit(1)

    print("\n--- Determinism smoke (1 Fixture C record) ---")

    # Dormant twice (live sampling, seed_all(SEED) at entry of each call).
    da = sampling_generate_dormant(model, tokenizer, prompt)
    db = sampling_generate_dormant(model, tokenizer, prompt)
    dorm_identical = bool(
        da["generated_ids"].shape == db["generated_ids"].shape
        and torch.equal(da["generated_ids"], db["generated_ids"])
    )
    print(f"  dormant  record_id={rid}: n_tokens={da['n_generated']} / "
          f"{db['n_generated']} identical={dorm_identical}")

    # Arm 1 active twice.
    aa = sampling_generate_active(
        model, tokenizer, prompt, non_prose_ids, spectral_threshold,
        kickstart_mode="production",
    )
    ab = sampling_generate_active(
        model, tokenizer, prompt, non_prose_ids, spectral_threshold,
        kickstart_mode="production",
    )
    act_identical = bool(
        aa["generated_ids"].shape == ab["generated_ids"].shape
        and torch.equal(aa["generated_ids"], ab["generated_ids"])
    )
    pr_a = [round(p["pr"], 6) for p in aa["pr_log"]]
    pr_b = [round(p["pr"], 6) for p in ab["pr_log"]]
    pr_identical = bool(pr_a == pr_b)
    print(f"  arm1     record_id={rid}: n_tokens={aa['n_generated']} / "
          f"{ab['n_generated']} identical={act_identical} "
          f"n_pr={len(pr_a)} pr_identical={pr_identical}")

    identical = bool(dorm_identical and act_identical and pr_identical)
    out = {
        "record_id": rid,
        "prompt_len": int(aa["prompt_len"]),
        "dormant_identical": str(dorm_identical),
        "active_identical": str(act_identical),
        "pr_identical": str(pr_identical),
        "identical": str(identical),
        "n_pr_values": int(len(pr_a)),
        "n_generated_active": int(aa["n_generated"]),
        "pr_a_first": pr_a[0] if pr_a else None,
        "pr_b_first": pr_b[0] if pr_b else None,
        "pr_a_last": pr_a[-1] if pr_a else None,
        "pr_b_last": pr_b[-1] if pr_b else None,
    }
    if not identical:
        print("[STOP] Determinism smoke FAILED: token ids or PR log differ "
              "across runs.")
        sys.exit(1)
    print("  determinism smoke: ALL IDENTICAL (dormant tokens, arm1 tokens, "
          "PR log @6dp)")
    return out


