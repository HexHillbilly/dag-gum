def compute_ds032_part2_metrics(
    records: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """Aggregate DS-032 Part 2 (suppression-only sampling) escape metrics."""
    n = len(records)
    n_rescue = 0
    n_gross = 0
    n_net = 0
    n_eos = 0
    escaped_n: List[int] = []
    buckets = {"1": 0, "2-23": 0, "24-127": 0, "128": 0}
    for r in records:
        active = r.get("active", {})
        n_gen = int(active.get("n_generated", 0))
        byte_id = bool(active.get("byte_identical_to_dormant", True))
        if active.get("delta_distinct_2", 0.0) > 0:
            n_rescue += 1
        if not byte_id:
            n_gross += 1
            escaped_n.append(n_gen)
            if n_gen == 1:
                buckets["1"] += 1
            elif n_gen < 24:
                buckets["2-23"] += 1
            elif n_gen < 128:
                buckets["24-127"] += 1
            else:
                buckets["128"] += 1
            if n_gen >= 24:
                n_net += 1
        if bool(active.get("eos_terminated", False)):
            n_eos += 1
    return {
        "n": n,
        "rescue_rate": float(n_rescue) / n,
        "gross_escape": float(n_gross) / n,
        "net_escape": float(n_net) / n,
        "eos_rate": float(n_eos) / n,
        "median_n_gen_escaped": float(np.median(escaped_n)) if escaped_n else float("nan"),
        "bucket_1": buckets["1"],
        "bucket_2_23": buckets["2-23"],
        "bucket_24_127": buckets["24-127"],
        "bucket_128": buckets["128"],
    }


