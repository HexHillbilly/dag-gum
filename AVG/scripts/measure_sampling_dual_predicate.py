def load_ds035_rescue_rates(
    path: Path,
    fixtures: Sequence[str],
) -> Tuple[Dict[str, float], Dict[str, Set[int]]]:
    """Load DS-035 greedy rescue rates AND rescued record-id sets (REUSE).

    Rescue rate = #ΔD2>0 / n (DS-033/DS-035 convention). DS-035 is the greedy
    dual-predicate gate (is_collapsed-gated actuation); its per-fixture rates
    are the greedy comparison column in Table 1.
    """
    counts: Dict[str, Dict[str, int]] = {}
    rescued_ids: Dict[str, Set[int]] = {fixture: set() for fixture in fixtures}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            if r.get("record_type"):
                continue
            fixture = r.get("fixture")
            if fixture not in fixtures:
                continue
            active = r.get("active", {})
            d2 = active.get("delta_distinct_2", 0.0)
            rec = counts.setdefault(fixture, {"n": 0, "n_rescue": 0})
            rec["n"] += 1
            if d2 > 0:
                rec["n_rescue"] += 1
                rescued_ids.setdefault(fixture, set()).add(int(r["record_id"]))
    rates: Dict[str, float] = {}
    for fixture in fixtures:
        rec = counts.get(fixture)
        if rec is None or rec["n"] == 0:
            raise SystemExit(
                f"[STOP] DS-035 has no records for fixture {fixture}."
            )
        rates[fixture] = float(rec["n_rescue"]) / float(rec["n"])
    return rates, rescued_ids


