    for fixture in fixtures_all:
        g = night008_fire[fixture]
        print(f"  {fixture}: fired={g['fired']} bigram_only={g['bigram_only']} "
              f"spectral_only={g['spectral_only']} both={g['both']} "
              f"(n={g['n']})")
    ds032_part2 = load_ds032_part2_baseline(DS032_JSONL)
    print(f"reused DS-032 Part 2 sampling baseline from {DS032_JSONL}: "
          f"heldout_v2 n={len(ds032_part2)}")

    # ------------------------------------------------------------------
    # Report-only: regenerate the markdown from the existing JSONL.
    # ------------------------------------------------------------------
    if args.report_only:
        if not OUTPUT_JSONL.exists():
            print(f"[STOP] --report-only: {OUTPUT_JSONL} does not exist.")
            sys.exit(1)
        print(f"\n--- report-only: regenerating {OUTPUT_MD} from "
              f"{OUTPUT_JSONL} ---")
        _, band_low = load_frozen_thresholds(FROZEN_THRESHOLDS_PATH)
        spectral_threshold = band_low
        all_results = load_jsonl(OUTPUT_JSONL)
        all_results = [r for r in all_results if "record_type" not in r]
        smoke: Dict[str, Any] = {
            "record_id": -1, "prompt_len": -1, "n_generated_active": -1,
            "n_pr_values": -1, "dormant_identical": "True",
            "active_identical": "True", "pr_identical": "True",
            "identical": "True", "all_identical": "True",
            "pr_a_first": None, "pr_b_first": None,
            "pr_a_last": None, "pr_b_last": None,
        }
        wall_clock_s: Any = "n/a (report-only regeneration of the night-014 run)"
        with open(OUTPUT_JSONL, encoding="utf-8") as f:
            for line in f:
                r = json.loads(line)
                if r.get("record_type") == "smoke":
                    smoke = {**smoke, **{k: v for k, v in r.items()
                                         if k != "record_type"}}
                elif r.get("record_type") == "meta" and "wall_clock_s" in r:
                    wall_clock_s = float(r["wall_clock_s"])
        ctx = build_ctx_from_results(
            all_results, ds035_rates, night008_fire, ds032_part2,
            device, dtype, smoke, spectral_threshold,
            wall_clock_s=wall_clock_s,
        )
        write_markdown_report(ctx)
        print(f"wrote {OUTPUT_MD} (report-only)")
        sys.exit(0)

    # ------------------------------------------------------------------
    # Frozen thresholds FIRST (Part A freeze); verify task-specified values.
    # ------------------------------------------------------------------
    t_pr, band_low = load_frozen_thresholds(FROZEN_THRESHOLDS_PATH)
    spectral_threshold = band_low  # DS-034e configuration: band_low is the
                                   # frozen spectral_collapse threshold.
    print(f"frozen T_PR(2)={t_pr:.6f} band_low(2)={band_low:.6f} loaded from "
          f"docs/gate23/FROZEN_THRESHOLDS.md")
    print(f"DS-034e spectral_collapse threshold = band_low = "
          f"{spectral_threshold:.6f}")

    # ------------------------------------------------------------------
    # Fixture data.
    # ------------------------------------------------------------------
    records_a = load_jsonl(T2S_DEG)  # Fixture A: t2s_degenerate
    records_b = load_jsonl(QWEN_DEG)  # Fixture B: qwen_degenerate
    records_c_all = load_jsonl(HELDOUT_DEG_V2)  # Fixture C: heldout_degenerate_v2

    # Fixture C: 50-record seeded subset (random.Random(42).sample, sorted).
    rng = random.Random(42)
    records_c = sorted(rng.sample(records_c_all, NUM_RECORDS_C),
                       key=lambda r: int(r["id"]))
    if args.max_records is not None:
        records_a = records_a[: args.max_records]
        records_b = records_b[: args.max_records]
        records_c = records_c[: args.max_records]
        print(f"[dev] capped records at {args.max_records} per fixture")
    print(f"Fixture A: {len(records_a)} t2s_degenerate | "
          f"Fixture B: {len(records_b)} qwen_degenerate | "
          f"Fixture C: {len(records_c)} heldout_degenerate_v2 (seeded subset)")

    # ------------------------------------------------------------------
    # Model load.
    # ------------------------------------------------------------------
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME, revision=MODEL_REVISION)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_NAME,
        revision=MODEL_REVISION,
        dtype=dtype,
    ).eval()
    if torch.cuda.is_available():
        model = model.to("cuda")
    print(f"model loaded on {model.device}")

    # Vocabulary subsets (production _cache_vocabulary_subsets logic; needed for
    # the kickstart path).
    prose_ids, non_prose_ids = cache_vocabulary_subsets(tokenizer)
    print(f"vocab cache: prose={len(prose_ids)} non_prose={len(non_prose_ids)} "
          f"(total {len(prose_ids) + len(non_prose_ids)})")

    # Determinism smoke FIRST (also serves as GPU warmup).
    smoke: Dict[str, Any] = {
        "record_id": -1, "prompt_len": -1, "n_generated_active": -1,
        "n_pr_values": -1, "dormant_identical": "True",
        "active_identical": "True", "pr_identical": "True",
        "identical": "True", "all_identical": "True",
        "pr_a_first": None, "pr_b_first": None,
        "pr_a_last": None, "pr_b_last": None,
    }
    if args.skip_smoke:
        print("\n--- Determinism smoke: skipped (dev) ---")
    else:
        try:
            smoke = run_determinism_smoke(
                model, tokenizer, records_c, "mutated_prompt",
                non_prose_ids, spectral_threshold,
            )
            smoke["all_identical"] = "True"
        except RuntimeError as e:
            if "out of memory" in str(e).lower():
                print(f"[STOP] CUDA out of memory during determinism smoke: {e}")
                sys.exit(1)
            raise

    # ==================================================================
    # Per-fixture runs: dormant (live sampling) + Arm 1 + Arm 2.
    # ==================================================================
    def run_fixture(
        fixture_name: str,
        records: List[Dict[str, Any]],
        prompt_key: str,
    ) -> List[Dict[str, Any]]:
        out: List[Dict[str, Any]] = []
        for rec_i, rec in enumerate(records):
            rid = int(rec["id"])
            prompt = rec[prompt_key]

            # Dormant (LIVE sampling baseline).
            gen_dorm = sampling_generate_dormant(model, tokenizer, prompt)
            dormant = build_dormant_meta(tokenizer, gen_dorm)

            # Arm 1 (production actuation).
            gen_a1 = sampling_generate_active(
                model, tokenizer, prompt, non_prose_ids, spectral_threshold,
                kickstart_mode="production",
            )
            arm1_active = build_active_meta(
                tokenizer, gen_a1, dormant, spectral_threshold, arm="arm1",
            )

            # Arm 2 (spectral-gated kickstart).
            gen_a2 = sampling_generate_active(
                model, tokenizer, prompt, non_prose_ids, spectral_threshold,
                kickstart_mode="spectral",
            )
            arm2_active = build_active_meta(
                tokenizer, gen_a2, dormant, spectral_threshold, arm="arm2",
            )

            out.append({
                "fixture": fixture_name,
                "record_id": rid,
                "prompt": prompt,
                "seed": SEED,
                "prompt_len": int(gen_dorm["prompt_len"]),
                "spectral_threshold": float(spectral_threshold),
                "dormant": dormant,
                "arm1_active": arm1_active,
                "arm2_active": arm2_active,
            })

            if (rec_i + 1) % 25 == 0 or rec_i == len(records) - 1:
                n_rescue_1 = sum(
                    1 for r in out if r["arm1_active"]["delta_distinct_2"] > 0
                )
                n_rescue_2 = sum(
                    1 for r in out if r["arm2_active"]["delta_distinct_2"] > 0
                )
                n_fire_1 = sum(
                    1 for r in out if r["arm1_active"]["fire_count"] > 0
                )
                n_kick_1 = int(sum(
                    r["arm1_active"]["n_kickstart_events"] for r in out
                ))
                n_kick_2 = int(sum(
                    r["arm2_active"]["n_kickstart_events"] for r in out
                ))
                print(f"  [{fixture_name}] {rec_i+1}/{len(records)}; "
                      f"rescue(arm1)={n_rescue_1} rescue(arm2)={n_rescue_2} "
                      f"fired(arm1)={n_fire_1} kick1={n_kick_1} kick2={n_kick_2}")
        return out

    all_results: List[Dict[str, Any]] = []
    try:
        print("\n--- Fixture A: t2s_degenerate (prompt key: record['text']) ---")
        part_a = run_fixture("t2s_degenerate", records_a, "text")
        all_results.extend(part_a)

        print("\n--- Fixture B: qwen_degenerate (prompt key: record['prompt']) ---")
        part_b = run_fixture("qwen_degenerate", records_b, "prompt")
        all_results.extend(part_b)

        print("\n--- Fixture C: heldout_degenerate_v2 (prompt key: "
              "record['mutated_prompt']) ---")
        part_c = run_fixture("heldout_degenerate_v2", records_c, "mutated_prompt")
        all_results.extend(part_c)
    except RuntimeError as e:
        if "out of memory" in str(e).lower():
            print(f"[STOP] CUDA out of memory during run: {e}")
            sys.exit(1)
        raise

    # ==================================================================
    # Aggregate (single source of truth).
    # ==================================================================
    ctx = build_ctx_from_results(
        all_results, ds035_rates, night008_fire, ds032_part2,
        device, dtype, smoke, spectral_threshold,
        wall_clock_s=time.time() - t_start,
    )
    tables = ctx["tables"]
    comparison = tables["comparison"]

    print("\n" + "=" * 70)
    print("NIGHT-014 SAMPLING DUAL-PREDICATE")
    for fixture, label in [("t2s_degenerate", "A t2s_degenerate"),
                           ("qwen_degenerate", "B qwen_degenerate"),
                           ("heldout_degenerate_v2", "C heldout_degenerate_v2")]:
        c = comparison[fixture]
        a1 = tables["escape"][fixture]["arm1_agg"]
        a2 = tables["escape"][fixture]["arm2_agg"]
        print(f"  {label}: greedy={c['greedy_rate']:.4f} "
              f"arm1={c['arm1_rate']:.4f} ({a1['n_rescue']}/{a1['n_records']}) "
              f"arm2={c['arm2_rate']:.4f} ({a2['n_rescue']}/{a2['n_records']})")
        print(f"    arm1 gross={a1['gross_escape']:.4f} net={a1['net_escape']:.4f} "
              f"EOS={a1['eos_rate']:.4f} kick={a1['mean_kickstart_events']:.2f} "
              f"supp={a1['mean_suppression_steps']:.1f}")
        print(f"    arm2 gross={a2['gross_escape']:.4f} net={a2['net_escape']:.4f} "
              f"EOS={a2['eos_rate']:.4f} kick={a2['mean_kickstart_events']:.2f} "
              f"supp={a2['mean_suppression_steps']:.1f}")
    print("=" * 70)

    # ==================================================================
    # Write outputs.
    # ==================================================================
    with open(OUTPUT_JSONL, "w", encoding="utf-8") as f:
        for r in all_results:
            f.write(json.dumps(r) + "\n")
        f.write(json.dumps({"record_type": "smoke", **smoke}) + "\n")
        f.write(json.dumps({
            "record_type": "meta",
            "model_name": MODEL_NAME,
            "model_revision": MODEL_REVISION,
            "device": device,
            "dtype": str(dtype),
            "torch_version": torch.__version__,
            "seed": SEED,
            "band_low": spectral_threshold,
            "sampling_temperature": SAMPLING_TEMPERATURE,
            "sampling_top_p": SAMPLING_TOP_P,
            "rescue_arm1_t2s": int(
                tables["escape"]["t2s_degenerate"]["arm1_agg"]["n_rescue"]
            ),
            "rescue_arm1_qwen": int(
                tables["escape"]["qwen_degenerate"]["arm1_agg"]["n_rescue"]
            ),
            "rescue_arm1_heldout_v2": int(
                tables["escape"]["heldout_degenerate_v2"]["arm1_agg"]["n_rescue"]
            ),
            "rescue_arm2_t2s": int(
                tables["escape"]["t2s_degenerate"]["arm2_agg"]["n_rescue"]
            ),
            "rescue_arm2_qwen": int(
                tables["escape"]["qwen_degenerate"]["arm2_agg"]["n_rescue"]
            ),
            "rescue_arm2_heldout_v2": int(
                tables["escape"]["heldout_degenerate_v2"]["arm2_agg"]["n_rescue"]
            ),
            "wall_clock_s": time.time() - t_start,
        }) + "\n")
    print(f"\nwrote {OUTPUT_JSONL} ({len(all_results)} record lines + "
          f"sidecar lines)")

    write_markdown_report(ctx)
    print(f"wrote {OUTPUT_MD}")

    print(f"\ntotal wall clock: {time.time() - t_start:.1f} s")
    print("night-014 measurement complete")


